"""A colour effect on a spell: what it is on the stack, and what becomes of it.

"Target spell or permanent becomes red" (the Lace cycle) recolours an object on
the stack. Three things about that record were wrong, all in one place, and all
measured on the tree before this file existed:

* **CR 400.7a.** The effect ended the moment the spell stopped being one.
  Chaoslace at a Grizzly Bears spell logged "(on the stack) became R" and put a
  green Bears onto the battlefield — the five Laces and Ersatz Gnomes' first
  ability, six shipped cards.
* **CR 105.2c.** Ersatz Gnomes' "target spell becomes colorless" stored the
  printed word and ``_stack_item_colors`` returned it: ``("colorless",)``, a
  non-empty answer to every reader asking whether the spell has a colour.
* **CR 613.7b.** The record had no timestamp and no duration, so there was
  nothing to carry.

The record is ``engine/color_changes.py``'s now — one writer, one reader, and
the carry onto the permanent through the same ``change_color`` every permanent
recolour goes through.
"""

from __future__ import annotations

import pytest

from engine import Game, PlayerState
from engine.color_changes import color_changes, recolor_spell, spell_color_change
from engine.models import Permanent
from tests.helpers import resolve_stack


def _duel():
    game = Game(players=[PlayerState(name="A"), PlayerState(name="B")])
    game.enforce_mana_costs = False
    return game


def _put(game, seat, card):
    permanent = Permanent(card=card)
    permanent.metadata["summoning_sickness_turn"] = -99
    game.players[seat].battlefield.append(permanent)
    game._sync_control()
    return permanent


def _bears_spell(game, catalog_by_name):
    """Seat 1 puts a Grizzly Bears spell on the stack; returns the object."""
    game.players[1].hand = [catalog_by_name["Grizzly Bears"]]
    assert game.queue_from_hand(1, "Grizzly Bears").supported
    return game.stack[-1]


@pytest.mark.cr("400.7a")
@pytest.mark.parametrize(
    "lace, colour",
    [
        ("Chaoslace", "R"),
        ("Deathlace", "B"),
        ("Lifelace", "G"),
        ("Purelace", "W"),
        ("Thoughtlace", "U"),
    ],
)
def test_400_7a_a_lace_on_a_permanent_spell_stays_on_the_permanent(
    catalog_by_name, lace, colour
):
    """"Effects … that change the characteristics … of a permanent spell on the
    stack continue to apply to the permanent that spell becomes." A Lace has no
    duration (CR 611.2a), so the creature is that colour for good."""
    game = _duel()
    spell = _bears_spell(game, catalog_by_name)
    game.players[0].hand = [catalog_by_name[lace]]

    assert game.queue_from_hand(0, lace, target_stack_index=0).supported
    assert game.resolve_top_of_stack()
    assert game._stack_item_colors(spell) == (colour,)
    resolve_stack(game)

    (bears,) = game.players[1].battlefield
    assert game._effective_colors(bears) == {colour}
    game.resolve_cleanup_step(1)
    assert game._effective_colors(bears) == {colour}


@pytest.mark.cr("400.7a", "105.2c")
def test_105_2c_a_spell_made_colourless_has_no_colour_and_neither_has_its_permanent(
    catalog_by_name,
):
    """Ersatz Gnomes: "{T}: Target spell becomes colorless." A colourless object
    has no colour — an empty set, not a sixth one — on the stack and on the
    battlefield the spell arrives on."""
    game = _duel()
    _put(game, 0, catalog_by_name["Ersatz Gnomes"])
    spell = _bears_spell(game, catalog_by_name)

    assert game.queue_permanent_ability(
        0, "Ersatz Gnomes", permanent_index=0, ability_index=0, target_stack_index=0,
    ).supported
    assert game.resolve_top_of_stack()

    assert spell_color_change(spell) == ()
    assert game._stack_item_colors(spell) == ()
    resolve_stack(game)
    (bears,) = game.players[1].battlefield
    assert game._effective_colors(bears) == set()


@pytest.mark.cr("105.2c")
def test_105_2c_a_colourless_spell_is_not_a_legal_answer_to_a_coloured_phrase(
    catalog_by_name,
):
    """The reader that mattered: a green creature spell the Gnomes made
    colourless is no longer "target green spell" — and it never becomes a
    spell of some colour called "colorless"."""
    game = _duel()
    # "{B}{B}: Counter target green spell."
    _put(game, 0, catalog_by_name["Deathgrip"])
    spell = _bears_spell(game, catalog_by_name)

    def offered():
        spec = game.activation_target_spec(0, 0)
        return [entry["name"] for entry in spec["valid_targets"]]

    assert offered() == ["Grizzly Bears"]
    recolor_spell(spell, "colorless")
    assert offered() == []
    assert "colorless" not in game._stack_item_colors(spell)


@pytest.mark.cr("613.7b", "400.7a")
def test_613_7b_the_carried_effect_keeps_the_timestamp_it_was_created_with(
    catalog_by_name,
):
    """"A continuous effect generated by the resolution of a spell or ability
    receives a timestamp at the time it's created" — when the Lace resolved,
    not when the creature arrived. So the permanent's colour effect carries the
    spell record's own stamp, and it is the indefinite slot it lands in."""
    game = _duel()
    spell = _bears_spell(game, catalog_by_name)
    game.players[0].hand = [catalog_by_name["Chaoslace"]]
    assert game.queue_from_hand(0, "Chaoslace", target_stack_index=0).supported
    assert game.resolve_top_of_stack()
    assert sorted(spell.choices["color_effect"]) == ["indefinite"]
    created = spell.choices["color_effect"]["indefinite"]["timestamp"]

    resolve_stack(game)
    (bears,) = game.players[1].battlefield
    (effect,) = color_changes(bears)
    assert effect["colors"] == ("R",)
    assert effect["timestamp"] == created
    assert effect["label"] == "colour change"


@pytest.mark.cr("400.7a", "611.2a")
def test_611_2a_a_turn_long_recolour_of_a_spell_ends_at_cleanup_on_the_permanent(
    catalog_by_name,
):
    """The duration an effect was created with is the duration it has on the
    permanent: "until end of turn" lands in the slot the cleanup step sweeps,
    and a Lace cast at the same spell earlier — a second effect, with no
    duration — is what is left when the turn-long one ends."""
    game = _duel()
    spell = _bears_spell(game, catalog_by_name)
    recolor_spell(spell, "W")
    recolor_spell(spell, "U", until_eot=True)
    assert game._stack_item_colors(spell) == ("U",)

    resolve_stack(game)
    (bears,) = game.players[1].battlefield
    assert game._effective_colors(bears) == {"U"}
    game.resolve_cleanup_step(1)
    assert game._effective_colors(bears) == {"W"}


@pytest.mark.cr("613.7b")
def test_613_7b_the_later_of_two_effects_on_a_spell_applies_last_either_way_round(
    catalog_by_name,
):
    """Timestamp order, not slot order: a Lace that resolves *after* a
    turn-long recolour is the later effect, so it is the spell's colour and
    the permanent's — during the turn as well as after it."""
    game = _duel()
    spell = _bears_spell(game, catalog_by_name)
    recolor_spell(spell, "U", until_eot=True)
    recolor_spell(spell, "W")
    assert game._stack_item_colors(spell) == ("W",)

    resolve_stack(game)
    (bears,) = game.players[1].battlefield
    assert game._effective_colors(bears) == {"W"}
    game.resolve_cleanup_step(1)
    assert game._effective_colors(bears) == {"W"}


@pytest.mark.cr("400.7a")
def test_400_7a_an_instant_takes_its_record_with_it(catalog_by_name):
    """Only a *permanent* spell becomes anything. A recoloured Lightning Bolt
    resolves, goes to the graveyard as the card it is, and no permanent on the
    battlefield is recoloured in its place."""
    game = _duel()
    bystander = _put(game, 1, catalog_by_name["Grizzly Bears"])
    game.players[1].hand = [catalog_by_name["Lightning Bolt"]]
    assert game.queue_from_hand(1, "Lightning Bolt", target_player_index=0).supported
    recolor_spell(game.stack[-1], "U")

    resolve_stack(game)

    assert game.players[0].life == 17
    assert game._effective_colors(bystander) == {"G"}
    assert [card.name for card in game.players[1].graveyard] == ["Lightning Bolt"]


# --- a copy of a spell: what it takes of the original's colour --------------


def _forked(game, catalog_by_name, name, **announcement):
    """Seat 1 casts *name*; seat 0 Forks it. Returns (original, copy)."""
    game.players[1].hand = [catalog_by_name[name]]
    assert game.queue_from_hand(1, name, **announcement).supported
    original = game.stack[-1]
    game.players[0].hand = [catalog_by_name["Fork"]]
    assert game.queue_from_hand(0, "Fork", target_stack_index=0).supported
    assert game.resolve_top_of_stack()
    (copy,) = [item for item in game.stack if item.is_copy]
    return original, copy


@pytest.mark.cr("707.9b")
def test_forks_copy_is_red_whatever_the_original_is(catalog_by_name):
    """"Copy target instant or sorcery spell, **except that the copy is red**."
    The rider nothing did: a Forked Ancestral Recall was a blue spell, to
    protection from blue and to "counter target red spell" alike."""
    game = _duel()

    original, copy = _forked(
        game, catalog_by_name, "Ancestral Recall", target_player_index=1
    )

    assert game._stack_item_colors(original) == ("U",)
    assert game._stack_item_colors(copy) == ("R",)


@pytest.mark.cr("707.2")
def test_a_copy_does_not_take_an_effect_that_recoloured_the_original(
    catalog_by_name,
):
    """A Lace on the original is an effect on that object, not a copiable value
    — and the record rides the choices a copy takes whole. The original stays
    what the Lace made it; the copy is what Fork makes it."""
    game = _duel()
    game.players[1].hand = [catalog_by_name["Lightning Bolt"]]
    assert game.queue_from_hand(1, "Lightning Bolt", target_player_index=0).supported
    bolt = game.stack[-1]
    recolor_spell(bolt, "U")
    recolor_spell(bolt, "G", until_eot=True)
    game.players[0].hand = [catalog_by_name["Fork"]]
    assert game.queue_from_hand(0, "Fork", target_stack_index=0).supported
    assert game.resolve_top_of_stack()
    (copy,) = [item for item in game.stack if item.is_copy]

    assert spell_color_change(bolt) == ("G",)
    assert spell_color_change(copy) == ("R",)
    assert set(copy.choices["color_effect"]) == {"indefinite"}
