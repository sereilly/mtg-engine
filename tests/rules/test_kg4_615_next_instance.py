def _rig_coin(monkeypatch, won: bool) -> None:
    from engine.handlers import control_flow

    monkeypatch.setattr(control_flow, "flip_coin", lambda win_probability=0.5: won)


@pytest.mark.cr("615.8", "614.1a")
@pytest.mark.parametrize("interactive", _SEATS)
@pytest.mark.parametrize("won", [True, False], ids=["won", "lost"])
def test_desperate_gambit_doubles_or_prevents_every_chunk_of_a_sweep(
    catalog_by_name, monkeypatch, interactive, won,
):
    """"Choose a source you control and flip a coin. If you win the flip, the
    next time that source would deal damage this turn, it deals double that
    damage instead. If you lose the flip, the next time it would deal damage
    this turn, prevent that damage." Alice's own Warmonger, its sweep: every
    chunk doubled (won) or prevented (lost); the next sweep is dealt
    normally."""
    _rig_coin(monkeypatch, won)
    game = _table(catalog_by_name, interactive, hand0=["Desperate Gambit"])
    monger = _put(game, catalog_by_name, 0, "Warmonger")
    wurm = _put(game, catalog_by_name, 0, "Craw Wurm")
    giant = _put(game, catalog_by_name, 1, "Hill Giant")
    assert game.queue_from_hand(0, "Desperate Gambit").supported
    if interactive:
        # A person is asked which source (a nobody-asked seat takes the first
        # permanent it controls, the Warmonger).
        game.resolve_top_of_stack(pause_for_choices=True)
        choice = game.pending_choice_of("permanent_choice")
        assert choice is not None and choice.player_index == 0, game.pending_choices
        assert game.resolve_pending_choice(
            "permanent_choice", 0, permanent_id=monger.permanent_id,
        )
    resolve_stack(game)
    assert "Desperate Gambit: chose Warmonger" in game.log, game.log

    _sweep(game, 0, "Warmonger")
    each = 2 if won else 0
    assert _damage(monger, wurm, giant) == [each, each, each], game.log
    assert _lives(game) == [20 - each, 20 - each], game.log

    _sweep(game, 0, "Warmonger")
    assert _damage(monger, wurm, giant) == [each + 1] * 3, game.log
    assert _lives(game) == [19 - each, 19 - each], game.log


def _to_declare_attackers(game):
    for permanent in game.all_permanents():
        permanent.metadata["summoning_sickness_turn"] = -99
    game.start_turn(0)
    game._close_current_priority_step()
    game.advance_combat_phase()
    game.advance_combat_phase()
    assert game.current_step == "declare_attackers", game.current_step


def _slot(game, seat, permanent) -> int:
    return next(
        index for index, perm in enumerate(game.controlled_by(seat))
        if perm is permanent
    )


def _to_combat_damage(game, attacker, blockers):
    """Seat 0 attacks with *attacker*; seat 1 blocks with *blockers*; the
    game stops at the combat damage step, before any damage is dealt."""
    _to_declare_attackers(game)
    slot = _slot(game, 0, attacker)
    assert game.declare_attackers(0, [slot])[0]
    resolve_stack(game)
    game.advance_combat_phase()
    assert game.declare_blockers(1, {_slot(game, 1, b): slot for b in blockers})[0]
    resolve_stack(game)
    return slot


