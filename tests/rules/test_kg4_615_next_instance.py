def test_pilgrim_of_justice_stops_a_red_sweep_whole_then_the_next_is_dealt(
    catalog_by_name, interactive,
):
    """"{W}, Sacrifice this creature: The next time a red source of your
    choice would deal damage this turn, prevent that damage." Named against
    Warmonger ("{2}: This creature deals 1 damage to each creature without
    flying and each player"): its first sweep reaches no creature and no
    player; its second is dealt normally."""
