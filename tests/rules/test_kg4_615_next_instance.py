@pytest.mark.cr("615.8", "616.1e")
def test_a_person_offered_the_open_shield_beside_another_spends_neither_twice(catalog_by_name):
    """CR 616.1 inside one dealing: the open shield is an applicable effect on
    every chunk of its instance, offered like any other. Alice (interactive)
    has Shadowbane against the Wumpus and a one-point shield on her Grizzly
    Bears: on the Bears' chunk both apply, and she is asked. Choosing
    Shadowbane spends nothing more — the one-point shield is still there —
    and the other chunks are prevented without a question."""
    game = _table(catalog_by_name, {0}, hand0=["Shadowbane"], active=1)
    bears = _put(game, catalog_by_name, 0, "Grizzly Bears")
    wurm = _put(game, catalog_by_name, 0, "Craw Wurm")
    wumpus = _put(game, catalog_by_name, 1, "Thrashing Wumpus")
    game.active_player_index = 0
    assert game.cast_from_hand(
        0, "Shadowbane", target_player_index=1,
        target_permanent_ids=[wumpus.permanent_id],
    ).supported
    resolve_stack(game)
    game.active_player_index = 1
    pool = add_shield(bears, make_numeric_pool(1, "a one-point shield"))

    assert game.queue_permanent_ability(1, "Thrashing Wumpus").supported
    game.resolve_top_of_stack(pause_for_choices=True)
    asked = 0
    while (choice := game.pending_choice_of("effect_order")) is not None:
        asked += 1
        assert choice.player_index == 0
        labels = [str(option) for option in choice.data["options"]]
        assert len(labels) == 2, labels
        index = next(i for i, label in enumerate(labels) if "chosen source" in label.lower())
        assert game.resolve_pending_choice("effect_order", 0, option_index=index)
    resolve_stack(game)

    assert asked == 1, "only the Bears' chunk has two applicable effects"
    assert _damage(bears, wurm) == [0, 0], game.log
    assert pool.amount == 1, "the one-point shield was not chosen and not spent"
    assert game.players[0].life == 23, game.log
    assert game.resume_stack == [] and game.pending_choices == []


