"""CR 615.8's "next instance of damage from that source" is the **whole
simultaneous dealing** — the project owner's ruling (2026-11-07):

    "CR 615.8 should prevent all damage from damage instances that affect
    multiple targets or all creatures."

CR 615.8: "Some prevention effects generated by the resolution of a spell or
ability refer to the next time a specific source would deal damage. These
effects prevent the next instance of damage from that source, regardless of how
much damage that is. Once an instance of damage from that source has been
prevented, any subsequent instances of damage that would be dealt by that
source are dealt normally." The engine deals damage in chunks — one source, one
recipient — and one instance from a source is every chunk it deals in one
simultaneous dealing (``engine/simultaneous_damage.py``): a sweep's, a split
sentence's, and the combat damage step's, one per strike pass (CR 510.2,
510.4). So a source-keyed "next time" spent on one chunk is open for the
source's other chunks of that dealing (``shields.SharedNextTime``,
``by_source``), and the dealing's finish closes it: the source's next dealing
is dealt normally. Two printed sentences are two instances (CR 608.2c).

Each board is driven at a table nobody is asked at and at one where the shield's
controller is an interactive seat. Validated backwards: on the base
(``1198d15e``) every "whole dealing" board fails — the shield, redirect or
rider is spent on the first chunk and the rest are dealt normally.
"""

from __future__ import annotations

import pytest

from engine import Game, PlayerState
from engine.models import Permanent
from engine.shields import make_numeric_pool, add_shield
from tests.helpers import resolve_stack


_SEATS = [pytest.param(set(), id="nobody-asked"), pytest.param({0, 1}, id="interactive")]


def _table(catalog_by_name, interactive, *, hand0=(), hand1=(), active=0):
    game = Game(players=[
        PlayerState(name="Alice", library=[catalog_by_name["Island"]] * 20),
        PlayerState(name="Bob", library=[catalog_by_name["Island"]] * 20),
    ])
    game.enforce_mana_costs = False
    game.interactive_seats = set(interactive)
    game.players[0].hand = [catalog_by_name[name] for name in hand0]
    game.players[1].hand = [catalog_by_name[name] for name in hand1]
    game.active_player_index = active
    game.current_turn_phase = "main1"
    return game


def _put(game, catalog_by_name, seat, name):
    permanent = Permanent(card=catalog_by_name[name])
    game._put_permanent_onto_battlefield(seat, permanent, None)
    permanent.metadata["summoning_sickness_turn"] = -99
    return permanent


def _damage(*permanents):
    return [permanent.damage_marked for permanent in permanents]


def _lives(game):
    return [player.life for player in game.players]


def _sweep(game, seat, name):
    """*name*'s "{…}: deals 1 damage to each creature … and each player"
    activated by *seat* and resolved."""
    result = game.activate_permanent_ability(seat, name)
    assert result.supported, result.details
    resolve_stack(game)


