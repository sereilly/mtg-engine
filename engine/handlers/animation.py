"""**Animation**: a permanent that "becomes an N/N creature" (CR 613 layers 4,
5, 6 and 7b at once) — the source, a target, every permanent a phrase names —
until end of turn, until end of combat, or indefinitely.

An animation is one **record** on the permanent, read by the CR 613 layer
bridge (``engine/layer_bridge.py``) and nothing else: the types it adds, its
size, its colours, the keywords and abilities it grants, each under the key
for its lifetime (:data:`ANIMATE_UNTIL_EOT`, :data:`ANIMATE_INDEFINITELY`,
:data:`ANIMATE_UNTIL_END_OF_COMBAT`). :func:`_animation_record` is the one
writer of it.

The animation half of ``engine/grammar/lowering/types.py``'s ``becomes`` verb;
what a permanent becomes when it gains a type without becoming a creature is
``types.py``'s. Split out of ``board_misc.py`` at the 2,000-line cap's split
round.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from ..color_changes import change_color
from ..continuous import next_timestamp
from ..keywords import grant_protection_flag
from ..oracle_types import _COLOR_WORD_TO_SYMBOL
from ..pt import set_base_pt
from ._amounts import count_from_payload, resolve_amount
from ._targets import resolve_target_permanent
from .registry import effect_handler

if TYPE_CHECKING:
    from ..game import Game
    from ..game_types import OracleExecutionContext
    from ..oracle import OracleInstruction


#: The one record a self-animation leaves, read by the CR 613 layer bridge and
#: swept at cleanup. A dict rather than a flag because the animation carries what
#: the permanent *becomes* — a creature, of some subtypes, with some keywords —
#: and a flag could only say that it became something.
ANIMATE_UNTIL_EOT = "animate_until_end_of_turn"

#: Its indefinite twin (Mishra's Groundbreaker, CR 611.2a). A **second key**
#: rather than a flag inside the record above, because what separates the two is
#: exactly which sweep can see it: `mixins/_constants._EOT_METADATA_KEYS` clears
#: the first at cleanup and knows nothing about the second. A flag would have
#: meant teaching that sweep to read the record it is deleting, which is the one
#: thing a key list cannot do.
ANIMATE_INDEFINITELY = "animate_indefinitely"

#: The **third** window (Jade Statue), and a third key for the second
#: one's reason: what separates the three is exactly which sweep can see
#: them. This one is cleared by the end-of-combat step, which is not the
#: cleanup step and matters because a turn may hold two combat phases
#: (Relentless Assault) — a Statue animated in the first must be an inert
#: artifact again for the second.
#:
#: The key's *name* is the one this engine has used since Jade Statue was a
#: card hook, and the sweep that pops it is unchanged. What changed is what
#: it holds: a bare ``True`` said only "it became something", so the layer
#: bridge answered "creature" and nothing else — the Statue was not a
#: **Golem**, so a Golem lord did not pump it and "destroy target Golem"
#: missed it. It now holds the same record its two siblings do, which is
#: what makes one layer-4 reader answer all three.
ANIMATE_UNTIL_END_OF_COMBAT = "animate_until_end_of_combat"


#: The payload keys an animation's *body* occupies. The sweep below hands
#: everything else to ``subject_matches`` as the noun phrase it animates, so a
#: key left off this list is a filter key that matcher has never heard of —
#: which is a narrowing dropped on a board-wide effect, the one direction
#: ``_lower_become_creature`` refuses outright.
_ANIMATION_PAYLOAD_KEYS = frozenset({
    "power", "toughness", "subtypes", "keywords", "card_types", "colors",
    "replaces_types", "granted_ability_lines", "pt_count",
    "protection_from_triggering_spell_colors",
})


def _animation_record(payload: dict) -> dict:
    """The record both animation handlers write, from the lowered payload.

    One builder because the handlers disagree about *which key* it goes on and
    about nothing else — which makes this the write API for an animation, the
    way ``type_changes.gain_types`` is for a gained type: **the stamp is in
    here**, so no animation can be recorded without one.

    CR 613.7b: "A continuous effect generated by the resolution of a spell or
    ability receives a timestamp at the time it's created." Every record, the
    additions too. Only a replacement used to carry one (CR 205.1a, "it
    becomes a 2/2 Gargoyle creature", against the "becomes an enchantment"
    printed to undo it), on the argument that additions commute — and they do
    with each other. They do not with an effect that *sets*: an addition that
    read as older than everything was applied before a card-type set whichever
    came first, so a permanent animated **after** it had been made an
    enchantment and nothing else would not have been a creature. No pair of
    cards in the pool arranges that today (the set effects aim at a creature,
    and what animates is aimed at a land or an artifact); the stamp is what
    keeps the next one from being ordered by which channel it was written on.

    ``replaces_types`` is still written only when the sentence claimed the
    replacement — the same rule the payload key itself follows.
    """
    record = {
        "subtypes": list(payload.get("subtypes") or ()),
        "keywords": list(payload.get("keywords") or ()),
        "card_types": list(payload.get("card_types") or ()),
        "timestamp": next_timestamp(),
    }
    if record["keywords"]:
        # Layer 6's half of the sentence has a place in that layer's order
        # (CR 613.7b): "…a 3/3 Sphinx creature **with flying**" resolved under
        # a Humility keeps the flying, and loses it to one that arrives later.
        # Its own key, so the layer-4 reader's ``timestamp`` below still means
        # what it meant.
        record["granted_at"] = next_timestamp()
    if payload.get("replaces_types"):
        record["replaces_types"] = True
    return record


def _animation_size(
    game: Game, payload: dict, context: OracleExecutionContext
) -> tuple[int, int]:
    """The P/T the body states, whichever of the three ways it states it.

    A printed number, an X the activation paid (Chimeric Staff), or — for
    Veiled Sentry — the mana value of the spell the trigger fired on, read
    through the same ``count_from_payload`` every other resolution-time
    quantity goes through. One reader, because all three animation handlers ask
    the same question and a second copy is a second chance for one of them to
    answer 0.
    """
    counted = payload.get("pt_count")
    if counted is not None:
        size = count_from_payload(game, context, counted)
        return size, size
    return (
        resolve_amount(payload.get("power", 0), context.x_value),
        resolve_amount(payload.get("toughness", 0), context.x_value),
    )


def _grant_animation_protection(
    perm, payload: dict, context: OracleExecutionContext
) -> None:
    """"…with protection from each of that spell's colors." (Opal Titan.)

    CR 702.16g: "protection from each of" a set of qualities is one protection
    ability per quality, so a colourless spell grants none and a two-coloured
    one grants two. Written on the ``protection_from_<word>`` channel every
    other granted protection uses (`mixins/protection._protection_qualities`),
    so the Titan's shield is read by the same code a printed one is.

    The colours are the spell's as the trigger froze it (CR 603.10): by the
    time the ability resolves the spell may have resolved or been countered,
    and the stack cannot be asked.

    No lifetime, because the animation has none — the Titan is a creature for
    the rest of the game and keeps what its own sentence gave it.
    """
    if not payload.get("protection_from_triggering_spell_colors"):
        return
    cast_card = (context.trigger_context or {}).get("cast_card")
    symbols = set(getattr(cast_card, "colors", None) or ())
    for word, symbol in _COLOR_WORD_TO_SYMBOL.items():
        if symbol in symbols:
            grant_protection_flag(perm, word)


def _grant_animation_abilities(
    perm, payload: dict, *, until_eot: bool
) -> None:
    """"…with "At the beginning of your upkeep, sacrifice this creature unless
    you pay {1}{U}."" (Veiled Apparition.)

    CR 613 layer 6 of the same sentence, on the one channel a *printed line*
    grant goes through (`engine/keywords.grant_ability_line`) — so the granted
    trigger reaches the upkeep step through the compiler, exactly as a printed
    one does, rather than through a second reader that would have to know what
    an animation granted.

    The duration is the animation's own, and it is the whole reason this is not
    a keyword write: a grant with no duration lasts as long as the object
    (CR 611.2c), which is what the Veiled cycle's permanent animation means,
    and an until-end-of-turn animation's ability has to be swept beside its
    body or the permanent keeps saying something it no longer is.
    """
    from ..keywords import grant_ability_line

    for line in payload.get("granted_ability_lines") or ():
        grant_ability_line(
            perm, str(line), duration="end_of_turn" if until_eot else None
        )


@effect_handler("animate_self_until_eot")
def animate_self_until_eot(game: Game, instruction: OracleInstruction, context: OracleExecutionContext) -> tuple[bool, str]:
    """"…becomes a 3/3 Sphinx creature with flying in addition to its other
    types until end of turn." (Riddleform, CR 613 layers 4, 6 and 7b.)

    The P/T is set through `engine/pt.py`, the single write API; everything else
    is *recorded* and read back by the layer bridge, so nothing is stashed and
    restored — the animation ends by the record being swept at cleanup, and the
    permanent's own types were never touched.

    "In addition to its other types" is why the record adds rather than
    replaces: the enchantment is still an enchantment while it is a creature.
    """
    return _animate_self(
        game, instruction, context,
        record_key=ANIMATE_UNTIL_EOT, until_eot=True, duration="until end of turn",
    )


@effect_handler("animate_self_indefinitely")
def animate_self_indefinitely(game: Game, instruction: OracleInstruction, context: OracleExecutionContext) -> tuple[bool, str]:
    """"{6}: This land becomes a 3/3 Elemental artifact creature that's still a
    land. (This effect lasts indefinitely.)" (Stalking Stones, CR 611.2a.)

    ``animate_target_indefinitely``'s self twin, and the two differences from
    the sibling above are both the duration, exactly as they are on the targeted
    pair: the record goes on the key the cleanup sweep does **not** clear, and
    the P/T on the persistent channel rather than the ``_until_eot`` one. A
    record on the swept key would end the effect the turn it started; a P/T on
    the swept channel would leave a land that is a creature with no size, which
    is a 0/0 the next state-based check bins under CR 704.5f.

    "That's still a land" needs no code for the targeted twin's reason: the
    record *adds* types (CR 613 layer 4 addition, not CR 305.7's replacement).
    """
    return _animate_self(
        game, instruction, context,
        record_key=ANIMATE_INDEFINITELY, until_eot=False, duration="indefinitely",
    )


def _animate_self(
    game: Game,
    instruction: OracleInstruction,
    context: OracleExecutionContext,
    *,
    record_key: str,
    until_eot: bool,
    duration: str,
) -> tuple[bool, str]:
    """Both self-animations: write the record on the source and log it.

    One body for ``_animate_target``'s reason one screen down — which record is
    written is the only thing the two kinds disagree about, and a second copy of
    the write is a second chance for the colour channel or the P/T channel to be
    given the wrong duration.
    """
    source = context.source_permanent
    if source is None:
        return False, "ability not implemented"
    payload = instruction.payload
    power, toughness = _animation_size(game, payload, context)
    set_base_pt(source, power, toughness, until_eot=until_eot)
    source.metadata[record_key] = _animation_record(payload)
    _grant_animation_abilities(source, payload, until_eot=until_eot)
    _grant_animation_protection(source, payload, context)
    _record_animation_colors(source, payload, until_eot=until_eot)
    # A permanent that became a creature is one a creature-scoped static now
    # reaches, and where that static applies is layer 4's question for the
    # whole board (CR 613.8a: "Creatures you control are the chosen type"
    # depends on this effect and applies after it). **Not recomputed here.**
    # The board a resolution leaves is recomputed once, at the seam every
    # resolution passes (``resolve_top_of_stack``) — this handler and five
    # like it each did their own for the round that seam did not exist, which
    # is a rule with as many fire sites as there are handlers that remember.
    game.log.append(
        f"{context.card.name} becomes a {power}/{toughness} creature {duration}"
    )
    return True, "resolved"


@effect_handler("animate_target_indefinitely")
def animate_target_indefinitely(game: Game, instruction: OracleInstruction, context: OracleExecutionContext) -> tuple[bool, str]:
    """"Target land becomes a 3/3 artifact creature that's still a land. (This
    effect lasts indefinitely.)" (Mishra's Groundbreaker, CR 611.2a.)

    The same animation as its until-end-of-turn twin below, written to the key
    the cleanup sweep does not clear and with the P/T on the **persistent**
    channel rather than the ``_until_eot`` one. Those are the only two
    differences, and both of them are the duration: a record on the swept key
    would end the effect the turn it started, and a P/T on the swept channel
    would leave a land that is a creature with no size — a 0/0 CR 704.5f puts
    in the graveyard at the next state-based check.

    Sharing the twin's body through :func:`_animate_target`, because which
    permanent it reaches, which narrowing it tests and what it logs are one
    question asked twice; only the record differs.
    """
    return _animate_target(
        game, instruction, context,
        record_key=ANIMATE_INDEFINITELY, until_eot=False, duration="indefinitely",
    )


@effect_handler("animate_target_until_eot")
def animate_target_until_eot(game: Game, instruction: OracleInstruction, context: OracleExecutionContext) -> tuple[bool, str]:
    """"Target snow land becomes a 2/2 creature until end of turn. It's still a
    land." (Balduvian Conjurer, CR 613 layers 4 and 7b.)

    The targeted twin of ``animate_self_until_eot`` above and the *same*
    record: an animation is one metadata entry the layer bridge reads, so
    animating something else is that entry on a different permanent and not a
    second mechanism. `engine/land_animation.py` is the third spelling of the
    same idea — a board-wide static recomputed from the board — and it is a
    table rather than an instruction for exactly that reason.

    "It's still a land" needs no code: the record *adds* types (CR 613 layer 4
    addition, not CR 305.7's replacement), so the land keeps everything it had.

    The P/T goes on the ``_until_eot`` channel, which the cleanup sweep clears
    alongside the type record — the source-animating sibling writes the
    persistent one, which is harmless on a permanent that stops being a
    creature the same moment but would leave a stamp on someone else's land.
    """
    return _animate_target(
        game, instruction, context,
        record_key=ANIMATE_UNTIL_EOT, until_eot=True, duration="until end of turn",
    )


def _record_animation_colors(perm, payload: dict, *, until_eot: bool) -> None:
    """"…becomes a 2/2 **green** creature" (Quirion Druid): CR 613 layer 5 of
    an animation sentence.

    A separate channel from the animation record because it is a separate
    layer, and the *same* one the laces write — through the same write API
    (``engine/color_changes.py``), so it is stamped when the animation resolves
    (CR 613.7b) and a later recolour of the animated land wins. "What colour is
    this permanent?" has one answer (``layer_bridge.collect_color_effects``),
    and an animation inventing a second would be two opinions about CR 105.3.

    Which of the two colour channels is the animation's own duration, for the
    reason the P/T write takes ``until_eot``: an indefinite animation whose
    colour wore off at cleanup would leave a green creature that is no longer
    green, and a turn-long one whose colour did not would leave the colour
    behind on a land that had stopped being a creature.

    Absent ``colors`` writes nothing at all. A sentence that named no colour
    said nothing about colour, which is not CR 105.2c's colourless — and
    writing an empty override would make every animated Assembly-Worker
    forcibly colourless.
    """
    colors = list(payload.get("colors") or ())
    if not colors:
        return
    change_color(perm, colors, until_eot=until_eot)


def _animate_target(
    game: Game,
    instruction: OracleInstruction,
    context: OracleExecutionContext,
    *,
    record_key: str,
    until_eot: bool,
    duration: str,
) -> tuple[bool, str]:
    """Both targeted animations: find the target, write the record, log it.

    One body because the two kinds differ only in *how long* — which permanent
    is reached, which narrowing is tested and what the log says are the same
    question either way, and a second copy of the target resolution is a second
    chance to disagree about what the printed noun phrase names.
    """
    from ..subject_filters import subject_matches

    filt = (instruction.payload.get("targets") or {}).get("filter") or {}
    target = resolve_target_permanent(
        game,
        context,
        predicate=lambda perm: subject_matches(
            game, perm, filt,
            observer=game.controller_index_of(context.source_permanent)
            if context.source_permanent is not None else None,
            source=context.source_permanent,
        ),
        fallback_on_invalid_choice=False,
    )
    if target is None:
        game.log.append(f"{context.card.name}: no land to animate")
        return True, "resolved"
    payload = instruction.payload
    power, toughness = _animation_size(game, payload, context)
    set_base_pt(target, power, toughness, until_eot=until_eot)
    target.metadata[record_key] = _animation_record(payload)
    _grant_animation_abilities(target, payload, until_eot=until_eot)
    _grant_animation_protection(target, payload, context)
    _record_animation_colors(target, payload, until_eot=until_eot)
    # See ``_animate_self``: layer 4 is decided for the whole board, at the
    # resolution seam.
    game.log.append(
        f"{target.card.name} becomes a {power}/{toughness} creature "
        f"{duration} ({context.card.name})"
    )
    return True, "resolved"


@effect_handler("animate_matching_until_eot")
def animate_matching_until_eot(game: Game, instruction: OracleInstruction, context: OracleExecutionContext) -> tuple[bool, str]:
    """"Forests you control become 2/3 creatures until end of turn. They're
    still lands." (Thelonite Druid, CR 613 layers 4 and 7b.)

    The swept twin of ``animate_target_until_eot`` above and the *same* record:
    an animation is one metadata entry the layer bridge reads, so animating a
    described set is that entry on every member and not a second mechanism.

    Which permanents is asked of ``subject_matches``, not of the pure matcher:
    "Forests **you control**" is a seat comparison no read of the land alone can
    make, and the observer is CR 109.5's — the controller of the ability, never
    whoever controls what it reaches. The lowering gates on the same key set, so
    a phrase this cannot test never arrives here; a dropped narrowing on a sweep
    is not an animation that does less, it is one that takes the board.

    CR 611.2c fixes the set when the ability resolves: a Forest played
    afterwards is not animated, and one that leaves takes its own record with
    it. The P/T goes on the ``_until_eot`` channel, which the cleanup sweep
    clears alongside the type record.
    """
    from ..subject_filters import subject_matches

    described = {
        key: value for key, value in instruction.payload.items()
        if key not in _ANIMATION_PAYLOAD_KEYS
    }
    observer = (
        game.players.index(context.caster) if context.caster in game.players else None
    )
    # "All lands **target player** controls become 3/3 creatures until end of
    # turn." (Jolrael, Empress of Beasts.) A seat the activation announced
    # (CR 601.2c), which no read of a land can supply — handed to the matcher
    # the way the tap and destroy sweeps hand it, because without it the
    # matcher refuses the word and the sweep animates nothing.
    targeted_seat = (
        game.players.index(context.target)
        if context.target is not None and context.target in game.players
        else None
    )
    payload = instruction.payload
    power, toughness = _animation_size(game, payload, context)
    record = _animation_record(payload)
    animated = []
    for permanent in game.all_permanents():
        if not subject_matches(
            game, permanent, described,
            observer=observer, source=context.source_permanent,
            targeted_player=targeted_seat,
        ):
            continue
        set_base_pt(permanent, power, toughness, until_eot=True)
        permanent.metadata[ANIMATE_UNTIL_EOT] = dict(record)
        _grant_animation_abilities(permanent, payload, until_eot=True)
        _grant_animation_protection(permanent, payload, context)
        _record_animation_colors(permanent, payload, until_eot=True)
        animated.append(permanent)
    if not animated:
        game.log.append(f"{context.card.name}: nothing to animate")
        return True, "resolved"
    # See ``_animate_self``: layer 4 is decided for the whole board, at the
    # resolution seam.
    game.log.append(
        f"{context.card.name} animated "
        + ", ".join(perm.card.name for perm in animated)
        + f" as {power}/{toughness} creatures until end of turn"
    )
    return True, "resolved"


@effect_handler("animate_self_until_end_of_combat")
def animate_self_until_end_of_combat(game: Game, instruction: OracleInstruction, context: OracleExecutionContext) -> tuple[bool, str]:
    """"{2}: This artifact becomes a 3/6 Golem artifact creature **until end of
    combat**." (Jade Statue.)

    The third self-animation, through the one body its two siblings share — and
    that is the whole of what this rewrite buys. It used to be a card hook
    carrying ``power=3, toughness=6`` and a bare ``True`` flag: the Statue got a
    size and the word "creature" and **no subtypes**, so it answered "no" to
    "is this a Golem" while it was one. A Golem lord did not pump it and
    "destroy target Golem" missed it.

    The P/T goes on the **persistent** channel (``until_eot=False``), which is
    the channel the end-of-combat sweep clears — the swept-at-cleanup one would
    leave the body a step too long, and the Statue is only ever a creature
    inside a combat.
    """
    return _animate_self(
        game, instruction, context,
        record_key=ANIMATE_UNTIL_END_OF_COMBAT, until_eot=False,
        duration="until end of combat",
    )
